def test_rendering_the_same_run_twice_gives_the_same_bytes() -> None:
    results, fixture = _results(_claim(), _claim(dataset="gasoline")), _fixture(_entry())
    assert parity_report.render(results, fixture) == parity_report.render(results, fixture)


def test_the_order_claims_arrived_in_does_not_change_the_report() -> None:
    """Tests may be selected, reordered or run in parallel; the report may not move."""
    first = _claim(dataset="corn", quantity="loadings")
    second = _claim(dataset="gasoline", quantity="scores")
    third = _claim(dataset="tecator", algorithm="pls", quantity="coefficients")
    fixture = _fixture(_entry())

    forwards = parity_report.render(_results(first, second, third), fixture)
    backwards = parity_report.render(_results(third, second, first), fixture)
    assert forwards == backwards


def test_a_partial_run_is_refused_rather_than_reported(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    """Rendering a subset would publish a coverage figure that is not true.

    `not_compared` lists comparable fixture entries that nothing checked. In a
    full run it is empty; in a `pytest -k` run it is not, and the report built
    from that would understate coverage while looking complete.
    """
    partial = tmp_path / "parity-results.json"
    partial.write_text(
        json.dumps({"not_compared": ["corn.pca.scores.sklearn"], "totals": {}, "results": []}),
        encoding="utf-8",
    )
    monkeypatch.setattr(parity, "RESULTS", partial)
    with pytest.raises(SystemExit, match="were not compared"):
        parity_report.main()
